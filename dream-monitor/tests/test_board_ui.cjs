const assert = require('node:assert/strict');
const B = require('../ui/board.js');
const now = 1900000000;
const base = { aid: '1', eligibility: 'eligible', sign_start: now+600, sign_end: now+8000,
  registration_phase: 'soon', quota: 50, can_join: false, joined_by_me: false };
const near = {...base, aid: 'near', sign_start: now+60, act_start: now+99999};
const far = {...base, aid: 'far', sign_start: now+900, act_start: now+100};
const open = {...base, aid: 'open', sign_start: now-500, registration_phase: 'open', can_join: true};
const full = {...base, aid: 'full', quota: 0};
const joined = {...base, aid: 'joined', joined_by_me: true};
const denied = {...base, aid: 'denied', eligibility: 'ineligible'};
const unknown = {...base, aid: 'unknown', eligibility: 'unknown'};
const noTime = {...base, aid: 'no-time', sign_start: null};
const closed = {...open, aid: 'closed', sign_end: now};
const all = [far, full, unknown, open, joined, denied, near, noTime, closed];
assert.deepEqual(B.list(all, 'eligible', now).map(r => r.aid), ['near', 'far', 'open', 'no-time']);
assert.deepEqual(B.list(all, 'soon', now).map(r => r.aid), ['near', 'far', 'no-time']);
assert.deepEqual(B.list(all, 'open', now).map(r => r.aid), ['open']);
assert.deepEqual(B.list(all, 'unknown', now).map(r => r.aid), ['unknown']);
assert.equal(B.list(all, 'all', now).length, all.length);
assert.deepEqual(B.counts(all, now), {all:9, eligible:4, soon:3, open:1, unknown:1});
assert.equal(B.pass({...open, can_join: 'false'}, 'eligible', now), false);
assert.equal(B.status(near, now+60), 'unknown');
assert.equal(B.status({...near, can_join:true}, now+60), 'open');
assert.equal(B.status(open, now+9000), 'closed');
assert.equal(B.countdown(now+61, now), '距开抢 1分 1秒');
assert.equal(B.countdown(now, now), '已到开抢时间');
assert.equal(B.countdown(null, now), '开抢时间待确认');
assert.deepEqual(all.map(r => r.aid), ['far','full','unknown','open','joined','denied','near','no-time','closed']);
console.log('Board UI: 14 offline assertions passed');
